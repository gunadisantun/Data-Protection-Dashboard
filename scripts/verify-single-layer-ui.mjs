import { createRequire } from "node:module";
import assert from "node:assert/strict";
import { mkdir, readFile } from "node:fs/promises";
const require = createRequire(process.env.PRIVACY_QA_RUNTIME + "/package.json");
const { chromium } = require("playwright");
const baseURL = "http://127.0.0.1:3100";
const browser = await chromium.launch({ channel: "msedge", headless: true });
const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
page.setDefaultTimeout(60000);
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
try {
  const setup = await context.request.get("/api/auth/desktop-setup", { timeout: 120000 });
  if ((await setup.json()).required) {
    const response = await context.request.post("/api/auth/desktop-setup", { data: { username: "assessmentqa", fullName: "Assessment QA", email: "assessmentqa@example.test", password: "QA-only-local-2026!", confirmPassword: "QA-only-local-2026!" } });
    assert(response.ok(), await response.text());
  }
  const login = await context.request.post("/api/auth/login", { data: { username: "assessmentqa", password: "QA-only-local-2026!" } });
  assert(login.ok(), await login.text());
  await page.goto("/self-assessment", { waitUntil: "networkidle", timeout: 120000 });
  await page.locator("select").first().selectOption({ index: 1 });
  await page.getByRole("button", { name: "Buka Assessment", exact: true }).click();
  await page.waitForURL(/self-assessment\/.+/);
  const id = page.url().split("/").filter(Boolean).at(-1);
  const questions = JSON.parse(await readFile("src/lib/self-assessment-controller-questions.json", "utf8"));
  const resetAnswers = Object.fromEntries(questions.map((q) => [q.id, { answer: "", note: "", pic: "", priority: "", evidenceFiles: [] }]));
  resetAnswers["M01-01"] = { answer: "Ada", note: "Archived QA response", pic: "", priority: "", evidenceFiles: [] };
  const reset = await context.request.patch(`/api/self-assessments/${id}`, { data: { answers: resetAnswers, status: "Draft" } });
  assert(reset.ok(), await reset.text());
  await page.reload({ waitUntil: "networkidle" });
  await page.getByRole("tab").first().waitFor();
  assert.equal(await page.getByRole("tab").count(), 7);
  assert(!(await page.locator("main").innerText()).match(/Level 1|Level 2|Terpicu dari L1/));
  const control = page.locator("section").filter({ has: page.getByRole("heading", { name: "Hak Subjek Data Pribadi", exact: true }) });
  const select = control.locator("select").first();
  assert.deepEqual(await select.locator("option").allTextContents(), ["Pilih jawaban", "Sudah Ada", "Dalam Proses", "Belum Ada", "Tidak Relevan"]);
  await select.selectOption("Sudah Ada");
  await control.locator("textarea").first().fill("Catatan pengujian penyimpanan.");
  await control.locator('input[type="file"]').first().setInputFiles({ name: "qa-evidence.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aZ1sAAAAASUVORK5CYII=", "base64") });
  await page.getByText("Bukti berhasil di-upload.", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Simpan", exact: true }).click();
  await page.getByText("Self assessment tersimpan.", { exact: true }).waitFor();
  await page.reload({ waitUntil: "networkidle" });
  assert.equal(await select.inputValue(), "Sudah Ada");
  assert.equal(await control.locator("textarea").first().inputValue(), "Catatan pengujian penyimpanan.");
  await control.getByRole("button", { name: "qa-evidence.png" }).waitFor();
  await mkdir("outputs/self-assessment-qa", { recursive: true });
  await page.screenshot({ path: "outputs/self-assessment-qa/desktop.png", fullPage: false });
  await control.scrollIntoViewIfNeeded();
  await page.screenshot({ path: "outputs/self-assessment-qa/controls.png", fullPage: false });
  await page.getByRole("tab", { name: /Larangan Penggunaan/ }).click();
  await page.getByText("Kontrol 56 - Pasal 66", { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByText("Kontrol 56 - Pasal 66", { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "outputs/self-assessment-qa/mobile.png", fullPage: false });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
  assert(!overflow, "Mobile horizontal overflow");
  const invalid = await context.request.patch(`/api/self-assessments/${id}`, { data: { status: "Submitted" } });
  assert.equal(invalid.status(), 400, "Incomplete submission must be rejected on server");
  const answers = Object.fromEntries(questions.map((q) => [q.id, { answer: "Sudah Ada", note: "", pic: "", priority: "", evidenceFiles: [] }]));
  const submit = await context.request.patch(`/api/self-assessments/${id}`, { data: { answers, status: "Submitted" } });
  assert(submit.ok(), await submit.text());
  const saved = (await (await context.request.get(`/api/self-assessments/${id}`)).json()).data;
  assert.equal(saved.answers["M01-01"].note, "Archived QA response");
  const finalize = await context.request.patch(`/api/self-assessments/${id}`, { data: { status: "Finalized" } });
  assert(finalize.ok(), await finalize.text());
  const download = await context.request.get(`/api/self-assessments/${id}/export`);
  assert(download.ok());
  assert((await download.body()).subarray(0, 4).toString() === "%PDF");
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ tabs: 7, controls: 56, saveReload: true, evidenceUpload: true, archivedAnswersPreserved: true, mobileOverflow: overflow, incompleteSubmission: invalid.status(), optionalEvidenceSubmit: submit.status(), finalize: finalize.status(), pdfExport: download.status(), browserErrors: errors }));
} finally {
  await browser.close();
}
