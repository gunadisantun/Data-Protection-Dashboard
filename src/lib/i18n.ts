type Dictionary = (typeof dictionaries)[Locale];
type DictionaryShape = typeof dictionaries.en;

export type TranslationKey = Paths<DictionaryShape>;

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "id";
}

export function getDictionary(locale: Locale) {
  return dictionaries[locale];
}

export function translate(locale: Locale, key: TranslationKey) {
  return translateFromDictionary(getDictionary(locale), key);
}

export function translateFromDictionary(dictionary: Dictionary, key: TranslationKey) {
  const value = key.split(".").reduce<unknown>((current, segment) => {
    if (current && typeof current === "object" && segment in current) {
      return (current as Record<string, unknown>)[segment];
    }
    return undefined;
  }, dictionary);

  return typeof value === "string" ? value : key;
}

type Paths<T> = T extends string
  ? never
  : {
      [K in keyof T & string]: T[K] extends string ? K : `${K}.${Paths<T[K]>}`;
    }[keyof T & string];
